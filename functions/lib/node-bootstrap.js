/**
 * Cloud-init user_data that turns a blank VPS into an enrolled, running
 * Arcana node with no human and no SSH involved.
 *
 * cloud-init only writes files and starts `arcana-node-bootstrap.service`.
 * That service -- not cloud-init's once-per-instance runcmd -- does the
 * work, so a reboot or crash at ANY point simply re-runs it, and every
 * stage below is idempotent:
 *
 *   ENROLL     generate the permanent API key ON the node, persist it
 *              (0600, atomic rename) BEFORE contacting the control plane,
 *              then bind its SHA-256 with the one-time enrollment token
 *              (functions/api/agent/enroll.js). The raw key never leaves
 *              the VPS; a crash after the server accepted the hash but
 *              before the node saw the 200 is recovered by re-sending the
 *              same hash (idempotent) or, after the token TTL, by proving
 *              the key with an authenticated heartbeat. The token is
 *              deleted from disk as soon as the key is bound.
 *   DNS_WAIT   wait until the node's hostname resolves to this VPS (the
 *              control plane publishes it right after the VPS is created;
 *              certbot's HTTP-01 challenge needs it).
 *   INSTALL    run the pinned singbox-vpn release installer, which itself
 *              checksum- and provenance-verifies the release before use,
 *              issues the Let's Encrypt certificate and installs renewal.
 *   AGENT      install + start vpn-provisioning-agent (heartbeat, jobs).
 *   HEALTH     run the installer's own local health check.
 *   COMPLETE   mark done; the unit's ConditionPathExists stops re-runs.
 *
 * Each stage is reported to POST /api/agent/bootstrap-status (after ENROLL,
 * authenticated with the node's own key) so operators see progress without
 * SSH. Neither the token nor the key is ever echoed to the journal, passed
 * on a command line (curl reads them from 0600 header files), or included
 * in a report.
 */

const NODE_ID = /^[a-z0-9][a-z0-9-]{1,62}$/;
const HOSTNAME = /^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const VERSION = /^v\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$/;
const HEX64 = /^[0-9a-f]{64}$/;
const REPO = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;

export const BOOTSTRAP_STAGES = ["ENROLL", "DNS_WAIT", "INSTALL", "AGENT", "HEALTH", "COMPLETE"];

function assertMatch(name, value, pattern) {
  if (typeof value !== "string" || !pattern.test(value)) {
    throw new Error(`node bootstrap: invalid ${name}`);
  }
}

function validWorkerUrl(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error("node bootstrap: invalid workerUrl");
  }
  if (url.protocol !== "https:" || url.username || url.password || url.search || url.hash) {
    throw new Error("node bootstrap: workerUrl must be a plain https origin");
  }
  return url.origin;
}

// Indent every line of a block for a YAML literal scalar.
function indent(text, spaces) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line) => (line.length ? pad + line : line))
    .join("\n");
}

export const BOOTSTRAP_SCRIPT = String.raw`#!/usr/bin/env bash
# Arcana node bootstrap -- generated by vpn-web functions/lib/node-bootstrap.js.
# Idempotent: safe to re-run after a crash or reboot at any point.
set -Eeuo pipefail
umask 077

ENV_FILE=/etc/arcana/bootstrap.env
STATE_DIR=/var/lib/arcana
AGENT_CONFIG=/etc/vpn/provisioning-agent.toml
AGENT_UNIT=/etc/systemd/system/vpn-provisioning-agent.service
DONE_MARKER="$STATE_DIR/bootstrap.done"

# shellcheck disable=SC1090
. "$ENV_FILE"
mkdir -p "$STATE_DIR" /etc/vpn
chmod 0700 "$STATE_DIR"

log() { echo "[arcana-bootstrap] $*"; }
CURRENT_STAGE=ENROLL
# Re-read explicitly: the line is deleted once enrollment succeeds, and this
# must not trip set -u on the re-runs that follow.
ENROLLMENT_TOKEN="$(sed -n 's/^ENROLLMENT_TOKEN=//p' "$ENV_FILE")"

agent_key() { sed -n 's/^agent_api_key = "\([0-9a-f]\{64\}\)"$/\1/p' "$AGENT_CONFIG" 2>/dev/null; }

# Writes "Authorization: Bearer <secret>" to a 0600 file for curl -H @file,
# so no secret ever appears in argv (/proc/*/cmdline) or the journal.
auth_header_file() {
  local f="$STATE_DIR/$1.hdr"
  printf 'Authorization: Bearer %s\n' "$2" > "$f"
  chmod 0600 "$f"
  echo "$f"
}

report() {
  local stage="$1" status="$2" message="$3" transport="" key hdr body
  [ "$#" -ge 4 ] && transport="$4"
  key="$(agent_key)"
  [ -n "$key" ] || return 0
  [ -f "$STATE_DIR/enrolled" ] || return 0
  message="$(printf '%s' "$message" | tr -cd 'A-Za-z0-9 _.,:/()=+-' | cut -c1-400)"
  if [ -n "$transport" ]; then
    body="$(printf '{"stage":"%s","status":"%s","message":"%s","transport":%s}' "$stage" "$status" "$message" "$transport")"
  else
    body="$(printf '{"stage":"%s","status":"%s","message":"%s"}' "$stage" "$status" "$message")"
  fi
  hdr="$(auth_header_file report "$key")"
  curl -fsS --connect-timeout 10 --max-time 20 -o /dev/null -X POST \
    -H @"$hdr" -H 'Content-Type: application/json' --data "$body" \
    "$WORKER_URL/api/agent/bootstrap-status" || log "stage report failed (non-fatal)"
}

on_error() {
  local rc=$?
  log "stage $CURRENT_STAGE failed (exit $rc); systemd will retry"
  report "$CURRENT_STAGE" FAILED "exit $rc"
  exit "$rc"
}
trap on_error ERR

write_agent_config() {
  local key="$1" tmp
  tmp="$(mktemp /etc/vpn/.provisioning-agent.toml.XXXXXX)"
  chmod 0600 "$tmp"
  cat > "$tmp" <<CFG
worker_url = "$WORKER_URL"
node_id = "$NODE_ID"
agent_api_key = "$key"
poll_interval_secs = 5
vpn_admin_binary = "/usr/local/bin/vpn-admin"
vpn_admin_config = "/etc/vpn/deployment.toml"
CFG
  sync "$tmp"
  mv -f "$tmp" "$AGENT_CONFIG"
  sync /etc/vpn
}

stage_enroll() {
  CURRENT_STAGE=ENROLL
  [ -f "$STATE_DIR/enrolled" ] && return 0
  # Persist the permanent key FIRST. If it already exists (a previous run
  # crashed after writing it), reuse it: the control plane may already have
  # bound its hash, and a new key would be rejected.
  if [ -z "$(agent_key)" ]; then
    write_agent_config "$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')"
  fi
  local key hash hdr code attempt=0
  key="$(agent_key)"
  hash="$(printf '%s' "$key" | sha256sum | cut -c1-64)"
  while :; do
    attempt=$((attempt + 1))
    code=0
    if [ -n "$ENROLLMENT_TOKEN" ]; then
      hdr="$(auth_header_file enroll "$ENROLLMENT_TOKEN")"
      code="$(curl -sS --connect-timeout 10 --max-time 30 -o "$STATE_DIR/enroll.out" -w '%{http_code}' \
        -X POST -H @"$hdr" -H 'Content-Type: application/json' \
        --data "{\"nodeId\":\"$NODE_ID\",\"apiKeySha256\":\"$hash\"}" \
        "$WORKER_URL/api/agent/enroll" || echo 000)"
      rm -f "$hdr"
    fi
    case "$code" in
      200) break ;;
      401|409|0)
        # Token spent/expired/absent. The key may still have been bound by
        # an earlier run whose response was lost: prove it directly.
        hdr="$(auth_header_file probe "$key")"
        if curl -fsS --connect-timeout 10 --max-time 20 -o /dev/null -X POST -H @"$hdr" \
             -H 'Content-Type: application/json' --data '{}' "$WORKER_URL/api/agent/heartbeat"; then
          rm -f "$hdr"; break
        fi
        rm -f "$hdr"
        log "enrollment rejected (HTTP $code) and key is not bound; a new enrollment token is required"
        return 1 ;;
      *)
        [ "$attempt" -ge 20 ] && { log "enrollment unreachable after $attempt attempts (last HTTP $code)"; return 1; }
        sleep $((attempt < 6 ? attempt * 5 : 30)) ;;
    esac
  done
  touch "$STATE_DIR/enrolled"
  # The token has done its job; never leave it on disk.
  sed -i '/^ENROLLMENT_TOKEN=/d' "$ENV_FILE"
  rm -f "$STATE_DIR/enroll.out"
  log "enrolled as $NODE_ID"
  report ENROLL OK "enrolled"
}

public_ipv4() {
  curl -fsS --max-time 5 http://169.254.169.254/hetzner/v1/metadata/public-ipv4 2>/dev/null \
    || curl -fsS --max-time 10 https://api.ipify.org
}

stage_dns_wait() {
  CURRENT_STAGE=DNS_WAIT
  [ -f "$STATE_DIR/dns.ok" ] && return 0
  report DNS_WAIT RUNNING "waiting for $PUBLIC_HOST"
  local ip resolved
  ip="$(public_ipv4)"
  for _ in $(seq 1 90); do
    resolved="$(getent ahostsv4 "$PUBLIC_HOST" | awk 'NR==1{print $1}' || true)"
    if [ -n "$resolved" ] && [ "$resolved" = "$ip" ]; then
      touch "$STATE_DIR/dns.ok"; report DNS_WAIT OK "$PUBLIC_HOST resolves to this host"; return 0
    fi
    sleep 10
  done
  log "$PUBLIC_HOST does not resolve to $ip after 15 minutes"
  return 1
}

# REALITY key files are written by install.sh's init_reality_keys (via the
# prebuilt vpn-admin binary) during stage_install, on this same node --
# nothing here regenerates or derives them. tls_server_name is the REALITY
# decoy/masquerade SNI (REALITY_HANDSHAKE_SERVER), never this node's own
# public hostname. reality_fingerprint and vless_flow are fixed deployment
# choices, not per-node data. Every fleet node also runs Hysteria2
# simultaneously (deployment.toml's [hysteria2] section) but nodes.transport
# is a single value -- this reports vless-reality only; Hysteria2 exposure
# via the route directory is a documented follow-up, not this pass.
# Absent/unreadable key files (e.g. an older install.sh) must never fail
# the INSTALL stage: falls back to an empty string, which report() treats
# as "no transport to include".
transport_report_json() {
  local pubkey short_id
  # base64 (public.key) and hex (short_id.txt) are both subsets of this
  # allowlist. A quote/backslash/newline from a corrupted file must never
  # reach the printf below -- bootstrap-status.js's JSON.parse fails the
  # WHOLE request (stage/status/message included) on malformed JSON, not
  # just these optional fields, the same reasoning report()'s own
  # message argument is already filtered through tr -cd for.
  pubkey="$(cat /etc/vpn/compat/reality/public.key 2>/dev/null | tr -cd 'A-Za-z0-9+/=' || true)"
  short_id="$(cat /etc/vpn/compat/reality/short_id.txt 2>/dev/null | tr -cd 'A-Za-z0-9+/=' || true)"
  if [ -z "$pubkey" ] || [ -z "$short_id" ]; then
    echo ""
    return 0
  fi
  printf '{"transport":"vless-reality","server_port":443,"tls_server_name":"%s","reality_public_key":"%s","reality_short_id":"%s","reality_fingerprint":"chrome","vless_flow":"xtls-rprx-vision"}' \
    "$REALITY_HANDSHAKE_SERVER" "$pubkey" "$short_id"
}

stage_install() {
  CURRENT_STAGE=INSTALL
  [ -f "$STATE_DIR/install.ok" ] && return 0
  report INSTALL RUNNING "installing singbox-vpn $SINGBOX_VPN_VERSION"
  local installer="$STATE_DIR/install.sh"
  curl -fsSL --connect-timeout 10 --max-time 120 --retry 5 --retry-connrefused -o "$installer" \
    "https://raw.githubusercontent.com/$SINGBOX_VPN_REPO/$SINGBOX_VPN_VERSION/install.sh"
  SINGBOX_VPN_VERSION="$SINGBOX_VPN_VERSION" SINGBOX_VPN_REPO="$SINGBOX_VPN_REPO" \
    bash "$installer" --non-interactive --domain "$PUBLIC_HOST" --role "$NODE_ROLE" --node-id "$NODE_ID" \
    --reality-handshake-server "$REALITY_HANDSHAKE_SERVER"
  [ -x /usr/local/bin/vpn-provisioning-agent ] || { log "release $SINGBOX_VPN_VERSION does not ship vpn-provisioning-agent"; return 1; }
  touch "$STATE_DIR/install.ok"
  report INSTALL OK "singbox-vpn $SINGBOX_VPN_VERSION installed" "$(transport_report_json)"
}

stage_agent() {
  CURRENT_STAGE=AGENT
  cat > "$AGENT_UNIT" <<'UNIT'
@@AGENT_UNIT@@
UNIT
  chmod 0644 "$AGENT_UNIT"
  systemctl daemon-reload
  systemctl enable --now vpn-provisioning-agent.service
  systemctl is-active --quiet vpn-provisioning-agent.service
  report AGENT OK "agent running"
}

stage_health() {
  CURRENT_STAGE=HEALTH
  for _ in $(seq 1 12); do
    if /usr/local/bin/vpn-health-check >/dev/null 2>&1; then
      report HEALTH OK "local health check passed"; return 0
    fi
    sleep 10
  done
  /usr/local/bin/vpn-health-check || true
  return 1
}

stage_enroll
stage_dns_wait
stage_install
stage_agent
stage_health
CURRENT_STAGE=COMPLETE
touch "$DONE_MARKER"
report COMPLETE OK "bootstrap complete"
log "bootstrap complete"
`;

