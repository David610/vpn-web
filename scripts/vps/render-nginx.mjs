#!/usr/bin/env node
// Renders the Nginx site configuration that replaces Cloudflare Pages' static
// hosting: the built `out/` directory, the SAME security headers and redirects
// the site ships in out/_headers and out/_redirects (including the per-build
// CSP nonce), and a reverse proxy to the Node API for /api, /v1 and /sub.
//   node scripts/vps/render-nginx.mjs --domain app.example.com --out out [--root /opt/arcana/current/site]
//                                     [--tls-dir /etc/letsencrypt/live/app.example.com] > arcana.conf
import { readFileSync } from "node:fs";
import path from "node:path";

export function parseHeaders(text) {
  const rules = [];
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    if (!/^\s/.test(raw)) { current = { pattern: raw.trim(), set: [], unset: [] }; rules.push(current); continue; }
    const line = raw.trim();
    if (line.startsWith("!")) current.unset.push(line.slice(1).trim().toLowerCase());
    else {
      const i = line.indexOf(":");
      current.set.push([line.slice(0, i).trim(), line.slice(i + 1).trim()]);
    }
  }
  return rules;
}

function matches(pattern, urlPath) {
  if (pattern.endsWith("/*")) return urlPath === pattern.slice(0, -2) || urlPath.startsWith(pattern.slice(0, -1));
  return urlPath === pattern;
}

// Cloudflare Pages semantics: every matching rule contributes; `! Name` removes
// whatever earlier rules added for that header; later values replace earlier ones.
export function headersFor(rules, urlPath) {
  const result = new Map();
  for (const rule of rules) {
    if (!matches(rule.pattern, urlPath)) continue;
    for (const name of rule.unset) result.delete(name);
    for (const [name, value] of rule.set) result.set(name.toLowerCase(), [name, value]);
  }
  return [...result.values()];
}

export function parseRedirects(text) {
  return text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith("#")).map((l) => {
    const [from, to, status = "302"] = l.split(/\s+/);
    return { from, to, status: Number(status) };
  });
}

const q = (value) => `"${String(value).replace(/(["\\$])/g, "\\$1")}"`;
const addHeaders = (list, indent) => list.map(([n, v]) => `${indent}add_header ${n} ${q(v)} always;`).join("\n");

export function renderNginx({ domain, root, tlsDir, headersText, redirectsText, upstream = "127.0.0.1:8787" }) {
  if (!/^[a-z0-9.-]+$/i.test(domain)) throw new Error("invalid domain");
  const rules = parseHeaders(headersText);
  const redirects = parseRedirects(redirectsText);
  const defaults = headersFor(rules, "/");
  const special = ["/telegram", "/admin"].map((prefix) => ({ prefix, headers: headersFor(rules, `${prefix}/x`) }));
  const staticTry = "try_files $uri $uri.html $uri/index.html =404;";
  const proxy = (extra = "") => `
        proxy_pass http://arcana_api;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_buffering off;
        proxy_read_timeout 60s;
        proxy_send_timeout 30s;
        client_max_body_size 1m;${extra}`;

  return `# Generated by scripts/vps/render-nginx.mjs - do not edit by hand.
upstream arcana_api {
    server ${upstream};
    keepalive 32;
}

limit_req_zone $binary_remote_addr zone=arcana_public:10m rate=20r/s;
limit_req_zone $binary_remote_addr zone=arcana_auth:10m rate=5r/s;
limit_conn_zone $binary_remote_addr zone=arcana_conn:10m;

server {
    listen 80;
    listen [::]:80;
    server_name ${domain};
    location /.well-known/acme-challenge/ { root /var/www/acme; }
    location / { return 301 https://$host$request_uri; }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${domain};

    ssl_certificate     ${tlsDir}/fullchain.pem;
    ssl_certificate_key ${tlsDir}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_timeout 1d;
    ssl_session_cache shared:arcana_ssl:10m;
    ssl_session_tickets off;

    server_tokens off;
    root ${root};
    limit_conn arcana_conn 40;
    error_page 404 /404.html;

${addHeaders(defaults, "    ")}
    add_header Strict-Transport-Security "max-age=31536000" always;

    location = /healthz { access_log off; proxy_pass http://arcana_api; }

${redirects.map((r) => `    location = ${r.from} { return ${r.status} ${r.to}; }`).join("\n")}

    # Dynamic API: same origin as the site, no CORS. Never cached.
    location /api/ {
        limit_req zone=arcana_public burst=40 nodelay;${proxy()}
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options "nosniff" always;
    }
    location /v1/ {
        limit_req zone=arcana_public burst=40 nodelay;${proxy()}
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options "nosniff" always;
    }
    location /sub/ {
        limit_req zone=arcana_auth burst=20 nodelay;${proxy()}
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options "nosniff" always;
    }
    # Agent long polls and node traffic have no per-IP burst limit of their own: the API caps in-flight work.
    location /api/agent/ {${proxy()}
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options "nosniff" always;
    }

    location /_next/static/ {
        add_header Cache-Control "public, max-age=31536000, immutable" always;
${addHeaders(defaults, "        ")}
        ${staticTry}
    }
${special.map(({ prefix, headers }) => `
    location = ${prefix} {
${addHeaders(headers, "        ")}
        ${staticTry}
    }
    location ${prefix}/ {
${addHeaders(headers, "        ")}
        ${staticTry}
    }`).join("\n")}

    location / {
        ${staticTry}
    }
}
`;
}

if (process.argv[1]?.endsWith("render-nginx.mjs")) {
  const arg = (name, fallback) => {
    const i = process.argv.indexOf(`--${name}`);
    return i > 0 ? process.argv[i + 1] : fallback;
  };
  const domain = arg("domain");
  const out = arg("out", "out");
  if (!domain) { console.error("--domain is required"); process.exit(2); }
  process.stdout.write(renderNginx({
    domain,
    root: arg("root", "/opt/arcana/current/site"),
    tlsDir: arg("tls-dir", `/etc/letsencrypt/live/${domain}`),
    headersText: readFileSync(path.join(out, "_headers"), "utf8"),
    redirectsText: readFileSync(path.join(out, "_redirects"), "utf8"),
  }));
}
